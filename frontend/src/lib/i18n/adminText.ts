/** Returns `tx(en)` — Bangla when the admin language is Bangla, else English. */
export function useAdminT() {
  const lang = useLanguageStore((s) => s.lang);
  return useCallback((en: string) => (lang === "bn" ? ADMIN_BN[en] ?? en : en), [lang]);
}
